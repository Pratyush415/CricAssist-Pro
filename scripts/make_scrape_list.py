"""One-off script: choose the matches and players to collect written context for.

Usage: python scripts/make_scrape_list.py [path/to/cricassist.db]

Writes src/cricassist/sources/scrape_list.json from the stats database, so
every entry is a match or player the stats tools also know. Cricsheet match
ids are ESPNcricinfo match ids, and players.cricinfo_id is the ESPNcricinfo
player id, so the scraper can build each page's address from the ids.

The list follows the demo questions (see ROADMAP.md): the matches and players
they mention first, then the biggest recent matches and most-capped players.
"""

import json
import sys
from pathlib import Path

from cricassist.config import load_settings
from cricassist.stats.db import connect

OUT = Path(__file__).resolve().parent.parent / "src" / "cricassist" / "sources" / "scrape_list.json"

DEMO_PLAYERS = ["Mohammed Shami", "DW Steyn", "V Kohli", "JJ Bumrah"]
DEMO_MATCHES = {
    1384439: "Demo Q6: 2023 World Cup final",
    1439892: "Kanpur Test, 2024 (in the test dataset)",
}

FINALS_SQL = """
    SELECT match_id, start_date, gender, event, team_1, team_2 FROM matches
    WHERE event_stage ILIKE 'final' AND start_date >= '2019-01-01'
      AND (collection IN ('ipl', 'wpl')
           OR event SIMILAR TO 'ICC (Men''s |Women''s )?(Cricket World Cup|World Cup|T20 World Cup|Champions Trophy|World Test Championship)')
    ORDER BY start_date
"""

KOHLI_2022_T20WC_SQL = """
    SELECT DISTINCT match_id, start_date, event, team_1, team_2 FROM batting_innings
    JOIN matches USING (match_id, start_date, event)
    WHERE player = 'V Kohli' AND event = 'ICC Men''s T20 World Cup' AND year(start_date) = 2022
    ORDER BY start_date
"""


def top_players(con, where: str, limit: int) -> list[tuple]:
    return con.execute(
        f"""SELECT p.player_id, p.name, p.full_name, p.cricinfo_id, p.country, count(*) AS matches
            FROM player_matches pm JOIN players p USING (player_id)
            WHERE p.cricinfo_id IS NOT NULL AND {where}
            GROUP BY ALL ORDER BY matches DESC LIMIT {limit}"""
    ).fetchall()


def main() -> None:
    db_path = Path(sys.argv[1]) if len(sys.argv) > 1 else load_settings().db_path
    con = connect(db_path)

    matches: dict[int, dict] = {}

    def add_match(match_id, start_date, event, team_1, team_2, reason):
        matches.setdefault(
            match_id,
            {"match_id": match_id, "date": str(start_date), "event": event, "teams": f"{team_1} v {team_2}", "reason": reason},
        )

    for match_id, reason in DEMO_MATCHES.items():
        row = con.execute("SELECT start_date, event, team_1, team_2 FROM matches WHERE match_id = ?", [match_id]).fetchone()
        add_match(match_id, *row, reason)
    for match_id, start_date, event, t1, t2 in con.execute(KOHLI_2022_T20WC_SQL).fetchall():
        add_match(match_id, start_date, event, t1, t2, "Demo Q3: Kohli at the 2022 T20 World Cup")
    for match_id, start_date, gender, event, t1, t2 in con.execute(FINALS_SQL).fetchall():
        add_match(match_id, start_date, event, t1, t2, f"Final ({gender}), since 2019")

    players: dict[str, dict] = {}

    def add_player(player_id, name, full_name, cricinfo_id, country, reason):
        players.setdefault(
            player_id,
            {"player_id": player_id, "name": name, "full_name": full_name, "cricinfo_id": cricinfo_id,
             "country": country, "reason": reason},
        )

    for name in DEMO_PLAYERS:
        row = con.execute("SELECT player_id, name, full_name, cricinfo_id, country FROM players WHERE name = ?", [name]).fetchone()
        add_player(*row, "Demo question")
    groups = [
        ("type = 'Intl' AND pm.gender = 'male' AND start_date >= '2019-01-01'", 60, "Most-capped men's international, 2019 on"),
        ("type = 'Intl' AND pm.gender = 'female' AND start_date >= '2019-01-01'", 20, "Most-capped women's international, 2019 on"),
        ("collection = 'ipl' AND start_date >= '2023-01-01'", 30, "Most IPL matches, 2023 on"),
    ]
    for where, limit, reason in groups:
        for player_id, name, full_name, cricinfo_id, country, _ in top_players(con, where, limit):
            add_player(player_id, name, full_name, cricinfo_id, country, reason)
            if len(players) >= 100:
                break

    out = {
        "note": "Pages to scrape for Cricinfo context (R4). Generated by scripts/make_scrape_list.py; "
        "check ESPNcricinfo's terms of use and robots.txt before fetching any of them.",
        "matches": list(matches.values()),
        "players": list(players.values()),
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", "utf-8", newline="\n")
    print(f"{len(matches)} matches, {len(players)} players -> {OUT}")


if __name__ == "__main__":
    main()
